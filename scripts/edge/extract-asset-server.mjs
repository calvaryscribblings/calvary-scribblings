// EDGE-2 — vendor the REAL Cloudflare Pages asset server out of git history, for tests/edge.
//
//   node scripts/edge/extract-asset-server.mjs        (re-run only to re-derive the vendor files)
//
// The wrangler package was committed by accident and removed in b65fa1ba. Its bundle,
// node_modules/wrangler/wrangler-dist/cli.js (wrangler 4.81.0), carries the open-source copy of the
// asset server Pages runs: ../pages-shared/asset-server/handler.ts (generateHandler: redirects,
// the asset lookup, serveAsset's write to the preservation store, notFound()'s read of it), its
// responses and rules engine, and the _redirects/_headers parsers that turn the two files into
// the metadata the handler reads. This copies those regions VERBATIM, found by their bundle
// markers (never by line number), adds the bundler's four helpers, and exports the entry points.
// The routing matcher for _routes.json (templates/pages-dev-util.ts) is copied with its types blanked.
//
// Nothing here is rewritten: a test that runs the vendored file runs wrangler's own lines.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../..', import.meta.url));
const COMMIT = 'b65fa1ba^';
const CLI = 'node_modules/wrangler/wrangler-dist/cli.js';
const UTIL = 'node_modules/wrangler/templates/pages-dev-util.ts';
const show = (p) => execFileSync('git', ['show', `${COMMIT}:${p}`], { cwd: ROOT, maxBuffer: 64 << 20 }).toString('utf8');
const blob = (p) => execFileSync('git', ['rev-parse', `${COMMIT}:${p}`], { cwd: ROOT }).toString().trim();

const version = JSON.parse(show('node_modules/wrangler/package.json')).version;
const lines = show(CLI).split('\n');
const at = (marker, from = 0) => {
  const i = lines.findIndex((l, n) => n >= from && l === marker);
  if (i < 0) throw new Error(`marker not found: ${marker}`);
  return i;
};
const region = (startMarker, endMarker) => {
  const s = at(startMarker);
  const e = at(endMarker, s + 1);
  return { s, e, text: lines.slice(s, e).join('\n') };
};

const parts = [
  region('// ../workers-shared/utils/configuration/constants.ts', '// ../workers-shared/utils/configuration/types.ts'),
  (() => {   // constructRedirects / constructHeaders: the region opens on a bare function, not a marker
    const s = lines.findIndex((l) => l === 'function constructRedirects({');
    const e = at('// ../pages-shared/metadata-generator/constants.ts', s);
    return { s, e, text: lines.slice(s, e).join('\n') };
  })(),
  region('// ../pages-shared/metadata-generator/constants.ts', '// ../pages-shared/environment-polyfills/index.ts'),
  region('// ../workers-shared/asset-worker/src/utils/rules-engine.ts', '// src/miniflare-cli/assets.ts'),
];

const head = `// GENERATED by scripts/edge/extract-asset-server.mjs — do not edit.
// Verbatim regions of wrangler ${version}'s bundle (${CLI}, blob ${blob(CLI)}, at ${COMMIT}):
${parts.map((p) => `//   lines ${p.s + 1}–${p.e}: ${lines[p.s]}`).join('\n')}
// wrangler is dual-licensed MIT / Apache-2.0 (Cloudflare, Inc.). Only the bundler helpers below are added.
/* eslint-disable */
var __defProp = Object.defineProperty;
var __getOwnPropNames = Object.getOwnPropertyNames;
var __name = (target, value) => __defProp(target, "name", { value, configurable: true });
var __esm = (fn2, res) => function __init() {
  return fn2 && (res = (0, fn2[__getOwnPropNames(fn2)[0]])(fn2 = 0)), res;
};
var __export = (target, all3) => { for (var name2 in all3) __defProp(target, name2, { get: all3[name2], enumerable: true }); };
var init_import_meta_url = () => {};
var init_handler2 = () => {};   // workers-shared/asset-worker/src/handler.ts — the rules engine's import, unused by it
`;
// Run every module initialiser the regions define, in order (esbuild's lazy __esm wrappers).
const inits = [...parts.map((p) => p.text).join('\n').matchAll(/^var (init_\w+) = __esm\(/gm)].map((m) => m[1]);
const tail = `
${inits.map((n) => `${n}();`).join('\n')}
export const WRANGLER_VERSION = ${JSON.stringify(version)};
export { generateHandler, createMetadataObject, parseRedirects, parseHeaders, ASSET_PRESERVATION_CACHE, CACHE_CONTROL_PRESERVATION };
`;
const out = `${ROOT}tests/edge/vendor/pages-asset-server.mjs`;
writeFileSync(out, head + parts.map((p) => p.text).join('\n\n') + tail);
// Its three type annotations are blanked by Node's own type stripper (whitespace in their place,
// nothing else touched), so it runs on any Node the CI uses.
writeFileSync(`${ROOT}tests/edge/vendor/pages-dev-util.mjs`,
  `// GENERATED by scripts/edge/extract-asset-server.mjs — ${UTIL} (wrangler ${version}, blob ${blob(UTIL)}), types stripped.\n// The _routes.json matcher wrangler's dev pipeline uses (templates/pages-dev-pipeline.ts).\n` + stripTypeScriptTypes(show(UTIL)));
console.log(`[extract] wrangler ${version}: ${parts.length} regions, ${parts.reduce((n, p) => n + p.e - p.s, 0)} lines`);
